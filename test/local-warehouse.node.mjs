// Start the CRM with `vite --mode local-crm` on a fresh local instance before running this test.
import assert from 'node:assert/strict'
import { test } from 'node:test'

const base = new URL(process.argv[2] || 'http://127.0.0.1:5181')
assert.equal(base.hostname, '127.0.0.1')
const api = '/api/local-warehouse'
async function request(path, { body, token, cookie, method } = {}) {
  const res = await fetch(new URL(path, base), {
    method: method || (body ? 'POST' : 'GET'),
    headers: { ...(body && { 'Content-Type': 'application/json' }), ...(token && { Authorization: `Bearer ${token}` }), ...(cookie && { Cookie: cookie }) },
    body: body ? JSON.stringify(body) : undefined,
  })
  return { status: res.status, data: await res.json(), cookie: res.headers.get('set-cookie')?.split(';')[0] }
}
async function login(account) {
  const { data, status } = await request('/api/auth/login', { body: { account, password: '123456' } })
  assert.equal(status, 200, account)
  return data.token
}
const line = (kind = 'roll', meters = 25, count = 1, stockId = 'demo-a') => ({ kind, meters, count, stockId, packaging: '' })
const form = (lines, other = {}) => ({ date: '2026-11-14', receiver: '仓库联测', lines, ...other })

test('warehouse: role isolation, handoff, transaction, cut and return, dealer exposure', async () => {
  const [owner, sales, other, warehouse, clerk] = await Promise.all(['admin', 'sales1', 'sales2', 'warehouse', 'clerk'].map(login))
  const post = (path, body, token) => request(`${api}/${path}`, { body, token })
  const view = async token => (await request(`${api}/`, { token })).data
  const getStock = async id => (await view(owner)).stocks.find(stock => stock.id === id)
  assert.equal((await request(`${api}/`)).status, 401)
  assert.equal((await request(`${api}/`, { token: clerk })).status, 403)
  assert.equal((await request(`${api}/dealer`, { token: owner })).status, 401)
  assert.equal((await post('dealer', { password: 'invalid' })).status, 401)
  const dealer = await post('dealer', { password: 'kingturf-local' })
  assert.equal(dealer.status, 200)
  const cookie = dealer.cookie
  const dealerView = async () => (await request(`${api}/dealer`, { cookie })).data
  assert.deepEqual((await dealerView()).stocks.map(stock => stock.id), ['demo-a'])
  assert.equal((await dealerView()).stocks[0].density, '15,750 簇/㎡')
  assert.equal((await dealerView()).stocks[0].visible, undefined)
  assert.equal((await request(`${api}/`, { cookie })).status, 401)

  const before = await getStock('demo-a')
  const noModel = await post('stock', { category: '景观草', code: 'TEST-NO-MODEL', name: '无型号测试草', width: 2, length: 25, rolls: 1 }, warehouse)
  assert.equal(noModel.status, 200)
  assert.equal((await view(owner)).stocks.find(stock => stock.code === 'TEST-NO-MODEL').rolls, 1)
  assert.equal((await view(sales)).customers.some(customer => customer.id === 'lead-b'), false)
  assert.deepEqual((await view(warehouse)).customers, [])
  assert.equal((await post('stock', { id: 'demo-a', rolls: 2 }, sales)).status, 403)
  assert.equal((await post('stock', { id: 'demo-a', rolls: 2, remnants: [{ meters: 26, count: 1 }] }, warehouse)).status, 400)
  assert.equal((await getStock('demo-a')).rolls, before.rolls)
  assert.equal((await post('orders', form([line()], { customerId: 'lead-b' }), sales)).status, 403)
  assert.equal((await post('orders', form([{ ...line(), price: 12 }]), warehouse)).status, 403)

  const body = form([line(), { ...line('cut', 7), price: 13 }, line('remnant', 7)], { customerId: 'lead-a' })
  const created = await post('orders', body, sales)
  assert.equal(created.status, 200)
  const { id } = created.data
  const action = (action, token = warehouse, data = {}) => post('dispatch', { id, action, ...data }, token)
  assert.equal((await view(other)).orders.some(order => order.id === id), false)
  assert.equal((await view(warehouse)).orders.find(order => order.id === id).lines[1].price, null)
  assert.equal((await action('ship', sales)).status, 403)
  assert.equal((await action('reject')).status, 400)
  assert.equal((await action('reject', warehouse, { reason: '核对包装' })).status, 200)
  assert.equal((await post('orders', { ...body, id }, other)).status, 404)
  assert.equal((await post('orders', { ...body, id }, sales)).status, 200)
  assert.equal((await action('logistics', warehouse, { driver: '司机', packaging: ['银色', '', ''] })).status, 200)
  const print = (priced, token) => request(`${api}/print?id=${id}&priced=${priced}`, { token })
  assert.equal((await print(0, sales)).status, 403)
  assert.equal((await print(1, warehouse)).status, 403)
  assert.equal((await print(1, owner)).data.lines[1].price, 13)
  assert.equal((await print(0, warehouse)).data.lines[1].price, null)
  assert.equal((await print(0, warehouse)).data.driver, '司机')
  const reserved = await getStock('demo-a')
  assert.equal(reserved.rolls, before.rolls)
  assert.equal(reserved.availableRolls, before.rolls - 2)
  assert.equal(reserved.reservedRolls, 2)
  assert.equal(reserved.availableRemnants[7], undefined)
  assert.equal((await post('stock', { id: 'demo-a', rolls: before.rolls, direction: 'out', reason: '不能占用锁定货物' }, warehouse)).status, 409)
  assert.equal((await dealerView()).stocks[0].rolls, before.rolls - 2)

  const confirmations = await Promise.all([action('ship'), action('ship')])
  assert.deepEqual(confirmations.map(result => result.status).sort(), [200, 409])
  let stock = await getStock('demo-a')
  assert.equal(stock.rolls, before.rolls - 2)
  assert.equal(stock.remnants[18], 1)
  assert.equal(stock.remnants[7], undefined)
  assert.equal((await dealerView()).stocks[0].rolls, stock.rolls)
  assert.equal((await action('return', warehouse, { reason: '客户退回全部' })).status, 200)
  assert.equal((await action('return', warehouse, { reason: '重复退回' })).status, 409)
  stock = await getStock('demo-a')
  assert.equal(stock.rolls, before.rolls - 1)
  assert.equal(stock.remnants[7], 2)
  assert.equal(stock.remnants[18], 1)

  const b = await getStock('demo-b')
  const conflicting = await Promise.all([1, 2].map(() => post('orders', form([line('roll', 25, b.rolls, b.id)]), warehouse)))
  assert.deepEqual(conflicting.map(result => result.status).sort(), [200, 409])
  const winner = conflicting.find(item => item.status === 200)
  assert.equal((await getStock(b.id)).availableRolls, 0)
  const loser = conflicting.find(item => item.status === 409)
  assert.ok(loser)
  assert.equal((await post('dispatch', { id: winner.data.id, action: 'ship' }, warehouse)).status, 200)
  assert.equal((await getStock(b.id)).rolls, 0)
  const invalid = await post('orders', form([line(), line('roll', 25, 1, b.id)]), warehouse)
  assert.equal(invalid.status, 409)
  assert.deepEqual(await getStock('demo-a'), stock)
  assert.equal((await post('stock', { id: 'demo-a', rolls: 1, remnants: [{ meters: 11, count: 2 }], visible: false }, warehouse)).status, 200)
  assert.equal((await getStock('demo-a')).remnants[11], 2)
  assert.equal((await dealerView()).stocks.length, 0)
  assert.equal((await request(`${api}/dealer`, { method: 'DELETE', cookie })).status, 200)
  assert.equal((await request(`${api}/dealer`, { cookie })).status, 401)
  const updated = await getStock('demo-a')
  assert.equal((await post('stock', { id: 'demo-a', rolls: 1, direction: 'out' }, warehouse)).status, 400)
  assert.equal((await post('stock', { id: 'demo-a', rolls: 1, direction: 'out', reason: '破损', remnants: [{ meters: 99, count: 1 }] }, warehouse)).status, 400)
  assert.deepEqual(await getStock('demo-a'), updated)
  assert.equal((await post('stock', { id: 'demo-a', rolls: updated.rolls + 1, direction: 'out', reason: '盘点' }, warehouse)).status, 409)
  assert.equal((await post('stock', { id: 'demo-a', rolls: 1, direction: 'out', reason: '破损', remnants: [{ meters: 11, count: 1 }] }, sales)).status, 403)
  assert.equal((await post('stock', { id: 'demo-a', rolls: 1, direction: 'out', reason: '破损', remnants: [{ meters: 11, count: 1 }] }, warehouse)).status, 200)
  const outgoing = await getStock('demo-a')
  assert.equal(outgoing.rolls, updated.rolls - 1)
  assert.equal(outgoing.remnants[11], updated.remnants[11] - 1)
  const cancellable = await post('orders', form([line()]), sales)
  assert.equal(cancellable.status, 200)
  assert.equal((await post('dispatch', { id: cancellable.data.id, action: 'cancel', reason: '越权' }, other)).status, 403)
  assert.equal((await post('dispatch', { id: cancellable.data.id, action: 'cancel', reason: '客户取消' }, sales)).status, 200)
  assert.equal((await post('dispatch', { id: cancellable.data.id, action: 'cancel', reason: '重复' }, sales)).status, 409)
  assert.equal((await getStock('demo-a')).availableRolls, outgoing.availableRolls)
  const rejectedCancel = await post('orders', form([line()]), sales)
  assert.equal(rejectedCancel.status, 200)
  assert.equal((await post('dispatch', { id: rejectedCancel.data.id, action: 'cancel' }, sales)).status, 400)
  assert.equal((await post('dispatch', { id: rejectedCancel.data.id, action: 'reject', reason: '待修改' }, warehouse)).status, 200)
  const freeBeforeCancel = await getStock('demo-a')
  assert.equal((await post('dispatch', { id: rejectedCancel.data.id, action: 'cancel', reason: '不再发货' }, sales)).status, 200)
  assert.deepEqual(await getStock('demo-a'), freeBeforeCancel)
  assert.equal((await post('dispatch', { id: rejectedCancel.data.id, action: 'ship' }, warehouse)).status, 409)
  assert.equal((await post('dispatch', { id: winner.data.id, action: 'cancel', reason: '已发货不能撤销' }, warehouse)).status, 409)
  const addMeterStock = await post('stock', { category: '景观草', code: 'METER-TEST', name: '按米测试', width: 2, length: 25, rolls: 2 }, warehouse)
  assert.equal(addMeterStock.status, 200)
  const meterStock = (await view(owner)).stocks.find(stock => stock.code === 'METER-TEST')
  const meterOrder = await post('orders', form([line('meter', 7, 1, meterStock.id)]), sales)
  assert.equal(meterOrder.status, 200)
  assert.equal((await getStock(meterStock.id)).reservedRolls, 1)
  assert.equal((await post('stock', { id: meterStock.id, rolls: 2, direction: 'out', reason: '试图扣锁库', autoMeters: true, remnants: [] }, warehouse)).status, 409)
  assert.equal((await post('dispatch', { id: meterOrder.data.id, action: 'ship' }, warehouse)).status, 200)
  assert.equal((await getStock(meterStock.id)).remnants[18], 1)
  assert.equal((await post('stock', { id: meterStock.id, direction: 'out', reason: '零货裁切', autoMeters: true, remnants: [{ meters: 5, count: 1 }] }, warehouse)).status, 200)
  const meterResult = await getStock(meterStock.id)
  assert.equal(meterResult.rolls, 1)
  assert.deepEqual(meterResult.remnants, { 13: 1 })
  assert.equal((await post('stock', { id: meterStock.id, direction: 'in', remnants: [{ meters: 25, count: 1 }, { meters: 3.5, count: 2 }] }, warehouse)).status, 200)
  assert.equal((await getStock(meterStock.id)).rolls, 2)
  assert.equal((await getStock(meterStock.id)).remnants['3.5'], 2)
})
